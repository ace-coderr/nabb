// Copies the NabbMarket ABI and recorded deployments from packages/contracts into
// src/generated/nabbMarket.ts so web and indexer never need a Hardhat build.
// Run after `pnpm --filter @nabb/contracts build` or a new deployment.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const contractsDir = path.resolve(here, "../../contracts");
const artifactPath = path.join(contractsDir, "artifacts/contracts/NabbMarket.sol/NabbMarket.json");
const deploymentsDir = path.join(contractsDir, "deployments");
const outFile = path.resolve(here, "../src/generated/nabbMarket.ts");

if (!existsSync(artifactPath)) {
  console.error(`Missing ${artifactPath}. Run \`pnpm --filter @nabb/contracts build\` first.`);
  process.exit(1);
}

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(path.join(deploymentsDir, file), "utf8"));
    if (d.contract !== "NabbMarket") continue;
    deployments[d.chainId] = {
      address: d.address,
      blockNumber: d.blockNumber,
      transactionHash: d.transactionHash,
    };
  }
}

const source = `// Generated by scripts/sync-contracts.mjs from packages/contracts. Do not edit by hand.

export const nabbMarketAbi = ${JSON.stringify(abi, null, 2)} as const;

export const nabbMarketDeployments = ${JSON.stringify(deployments, null, 2)} as const;
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, source);
console.log(
  `Wrote ${path.relative(process.cwd(), outFile)} (${abi.length} ABI entries, chains: ${Object.keys(deployments).join(", ") || "none"})`,
);
